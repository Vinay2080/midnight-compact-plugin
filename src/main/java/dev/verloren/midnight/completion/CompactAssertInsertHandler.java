package dev.verloren.midnight.completion;

import com.intellij.codeInsight.AutoPopupController;
import com.intellij.codeInsight.completion.InsertHandler;
import com.intellij.codeInsight.completion.InsertionContext;
import com.intellij.codeInsight.editorActions.TabOutScopesTracker;
import com.intellij.codeInsight.lookup.LookupElement;
import com.intellij.codeInsight.template.impl.TemplateManagerImpl;
import com.intellij.codeInsight.template.impl.TemplateState;
import com.intellij.openapi.application.ApplicationManager;
import com.intellij.openapi.command.WriteCommandAction;
import com.intellij.openapi.editor.Document;
import com.intellij.openapi.editor.Editor;
import com.intellij.openapi.project.Project;
import org.jetbrains.annotations.NotNull;

/**
 * Insert handler for the Compact {@code assert} keyword that automatically constructs
 * expression parentheses {@code ()}, positions the caret inside for immediate predicate
 * authoring, registers tab-out navigation, and coordinates auto-popup completion.
 *
 * <h3>IntelliJ Platform Lifecycle &amp; Threading Contract</h3>
 * <ul>
 *   <li><b>Subsystem Role:</b> {@link InsertHandler} implementation attached to {@code assert}
 *       lookup elements generated by {@code CompactKeywordCompletionProvider}.</li>
 *   <li><b>Calling Pipeline:</b> Invoked directly by IntelliJ's completion infrastructure
 *       ({@code com.intellij.codeInsight.completion.CodeCompletionHandlerBase} and
 *       {@code com.intellij.codeInsight.lookup.impl.LookupImpl}) immediately after the
 *       {@code assert} token is committed to the editor document.</li>
 *   <li><b>Threading Model:</b> Executed synchronously on the Event Dispatch Thread (EDT)
 *       within an active Write Action command context. Deferred re-anchoring logic is
 *       dispatched via {@link ApplicationManager#getApplication()}'s {@code invokeLater}
 *       and wrapped inside a {@link WriteCommandAction} to satisfy document modification locks.</li>
 *   <li><b>Cancellation &amp; Lifecycle Safety:</b> Guards against asynchronous editor disposal
 *       by verifying {@code !editor.isDisposed()} prior to triggering post-template caret
 *       relocation and popup triggers.</li>
 * </ul>
 *
 * <h3>Design Decisions &amp; Architectural Rationale</h3>
 * <ul>
 *   <li><b>Singleton Pattern:</b> Instantiated as an immutable, stateless singleton
 *       ({@link #INSTANCE}) with a private constructor to eliminate garbage collection
 *       overhead during high-frequency typing and completion lookup cycles.</li>
 *   <li><b>Memory Leak Prevention:</b> Strictly retains zero references to {@link Project},
 *       {@link Editor}, {@link Document}, or {@link LookupElement} instances within the field state;
 *       all context is transiently consumed through {@link InsertionContext}.</li>
 * </ul>
 *
 * <h3>Grammar &amp; Edge-Case Mitigations</h3>
 * <ul>
 *   <li><b>Duplicate Parenthesis Avoidance:</b> Scans ahead past intermediate whitespace.
 *       If an opening parenthesis {@code '('} is already present (e.g. completing before
 *       existing code {@code (x != 0, "error");}), insertion of duplicate {@code "()"} is
 *       bypassed and the caret is advanced cleanly into the existing expression boundary.</li>
 *   <li><b>Tab-Out Scopes:</b> Registers an empty scope with {@link TabOutScopesTracker} allowing
 *       the developer to press {@code [Tab]} to exit beyond the closing parenthesis {@code ')'}
 *       without inserting literal tab spaces.</li>
 *   <li><b>Live Template Race Mitigation:</b> When invoked inside an active Live Template session
 *       (e.g., circuit or function body skeleton), {@link TemplateState} advances or finalizes
 *       synchronously, which threatens to displace the caret to the end of the template.
 *       An {@link ApplicationManager#getApplication()#invokeLater} callback re-anchors the caret
 *       at the interior target offset once template execution settles.</li>
 * </ul>
 *
 * <h3>Request &amp; Execution Pipeline</h3>
 * <pre>{@code
 *   Lookup Selection [assert]
 *          │
 *          ▼
 *   handleInsert(context) ──► Lookahead past whitespace for '('
 *          │                          │
 *          ├─ Missing '(' ────────────┴─► Found '('
 *          ▼                                │
 *     Insert "()" & compute target          │
 *          │                                │
 *          └───────────────┬────────────────┘
 *                          ▼
 *             Position Caret at (|)
 *                          │
 *       ┌──────────────────┴──────────────────┐
 *       ▼                                     ▼
 *   Register Tab-Out Scope          Schedule Auto-Popup
 *       │
 *       ▼
 *   TemplateState Active? ──► [invokeLater] Re-anchor Caret inside ()
 * }</pre>
 *
 * @see InsertHandler
 * @see InsertionContext
 * @see TabOutScopesTracker
 * @see AutoPopupController
 * @see TemplateManagerImpl
 */
public final class CompactAssertInsertHandler implements InsertHandler<LookupElement> {

  /**
   * Shared stateless singleton instance for {@code assert} completion insertion.
   */
  public static final CompactAssertInsertHandler INSTANCE = new CompactAssertInsertHandler();

  /**
   * Private constructor enforcing singleton usage and preventing external instantiation.
   */
  private CompactAssertInsertHandler() {}

  /**
   * Handles post-completion document mutation for the {@code assert} keyword.
   *
   * @param context the insertion context containing document, editor, and offset metadata
   * @param item    the selected assertion lookup element
   */
  @Override
  @SuppressWarnings("DuplicatedCode")
  public void handleInsert(@NotNull InsertionContext context, @NotNull LookupElement item) {
    Editor editor = context.getEditor();
    Document document = context.getDocument();
    int tailOffset = context.getTailOffset();
    Project project = context.getProject();
    CharSequence chars = document.getCharsSequence();

    // Step 1: Lookahead forward past any whitespace to check if '(' already follows
    // the inserted assertion keyword (e.g. when completing right before existing argument expressions).
    // This prevents inserting duplicate parentheses like assert()(cond, "msg").
    int offset = tailOffset;
    while (offset < chars.length() && Character.isWhitespace(chars.charAt(offset))) {
      offset++;
    }
    boolean hasParen = offset < chars.length() && chars.charAt(offset) == '(';

    // Step 2: Conditionally insert parentheses and calculate target caret offset
    int caretTarget;
    if (!hasParen) {
      document.insertString(tailOffset, "()");
      caretTarget = tailOffset + 1; // Position cursor inside: assert(|)
    } else {
      caretTarget = offset + 1;      // Step inside existing open parenthesis
    }

    // Step 3: Relocate the caret directly inside the parentheses
    editor.getCaretModel().moveToOffset(caretTarget);

    // Step 4: Register Tab-Out scope to enable [Tab] key navigation past closing ')'
    TabOutScopesTracker.getInstance().registerEmptyScopeAtCaret(editor);

    // Step 5: Schedule auto-popup to immediately suggest argument expressions and identifiers
    AutoPopupController.getInstance(project).scheduleAutoPopup(editor);

    // Step 6: Mitigate Live Template synchronization races.
    // If a live template is currently active in the editor (e.g. from declaration templates),
    // TemplateState advances or finishes synchronously on lookup selection, which would otherwise
    // displace the caret past the end of the template (after the semicolon or closing brace).
    // We schedule caret repositioning onto the EDT via invokeLater to guarantee the cursor remains
    // inside the parentheses with argument suggestions visible.
    TemplateState templateState = TemplateManagerImpl.getTemplateState(editor);
    if (templateState != null) {
      ApplicationManager.getApplication().invokeLater(() -> {
        if (!editor.isDisposed()) {
          WriteCommandAction.runWriteCommandAction(project, () -> {
            if (!editor.isDisposed()) {
              editor.getCaretModel().moveToOffset(caretTarget);
              TabOutScopesTracker.getInstance().registerEmptyScopeAtCaret(editor);
              AutoPopupController.getInstance(project).scheduleAutoPopup(editor);
            }
          });
        }
      });
    }
  }
}
